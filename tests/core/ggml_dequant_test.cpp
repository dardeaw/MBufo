namespace core = gufo::core;
namespace quant = gufo::quant;
using namespace gufo::quant;

void TestRocmFP4Fast() {
  static_assert(sizeof(block_q4_0_rocmfp4) == 18, "rocmfp4 block must be 18");
  static_assert(sizeof(block_q4_0_rocmfp4_fast) == 17,
                "rocmfp4 fast block must be 17");
  static_assert(sizeof(block_q3_0_rocmfpx) == 14, "rocmfp3 block must be 14");
  if (quant::EncodedSizeBytes(core::GgmlType::kQ4_0_ROCMFP4_FAST, 256) != 136 ||
      quant::EncodedSizeBytes(core::GgmlType::kQ4_0_ROCMFP4, 256) != 144 ||
      quant::EncodedSizeBytes(core::GgmlType::kQ3_0_ROCMFPX, 256) != 112 ||
      quant::EncodedSizeBytes(core::GgmlType::kQ4_0_ROCMFP4_FAST, 257) != 0) {
    std::cerr << "Assertion failed: rocmfp size contract\n";
    std::exit(1);
  }

  float deq[512];
  DequantizeQ4_0_ROCMFP4_FAST(kFastBytes, deq, 512);
  for (std::size_t i = 0; i < 512; ++i) {
    if (std::memcmp(&deq[i], &kFastDequant[i], sizeof(float)) != 0) {
      std::cerr << "Assertion failed: rocmfp4 fast dequant bit mismatch at "
                << i << " actual=" << deq[i] << " expected=" << kFastDequant[i]
                << '\n';
      std::exit(1);
    }
  }
  DequantizeQ4_0_ROCMFP4(kDualBytes, deq, 512);
  for (std::size_t i = 0; i < 512; ++i) {
    if (std::memcmp(&deq[i], &kDualDequant[i], sizeof(float)) != 0) {
      std::cerr << "Assertion failed: rocmfp4 dual dequant bit mismatch at "
                << i << '\n';
      std::exit(1);
    }
  }
  DequantizeQ3_0_ROCMFPX(kFp3Bytes, deq, 512);
  for (std::size_t i = 0; i < 512; ++i) {
    if (std::memcmp(&deq[i], &kFp3Dequant[i], sizeof(float)) != 0) {
      std::cerr << "Assertion failed: rocmfp3 dequant bit mismatch at " << i
                << '\n';
      std::exit(1);
    }
  }

  if (ValidateQ4_0_ROCMFP4_FAST(kFastBytes, sizeof(kFastBytes)) != kFastValid) {
    std::cerr << "Assertion failed: fast validate golden\n";
    std::exit(1);
  }
  if (ValidateQ3_0_ROCMFPX(kFp3Bytes, sizeof(kFp3Bytes)) != kFp3Valid) {
    std::cerr << "Assertion failed: fp3 validate golden\n";
    std::exit(1);
  }
  std::uint8_t bad_scale[17] = {0};
  bad_scale[16] = 0x7F;
  if (ValidateQ4_0_ROCMFP4_FAST(bad_scale, 17) || kFastBadValid) {
    std::cerr << "Assertion failed: 0x7f scale must be invalid\n";
    std::exit(1);
  }
  std::uint8_t ok_scale[17] = {0};
  ok_scale[16] = 0x7E;
  if (ValidateQ4_0_ROCMFP4_FAST(ok_scale, 17) != kFastOkValid) {
    std::cerr << "Assertion failed: 0x7e scale must be valid\n";
    std::exit(1);
  }
  if (ValidateQ4_0_ROCMFP4_FAST(kFastBytes, sizeof(kFastBytes) - 1)) {
    std::cerr << "Assertion failed: misaligned fast row must fail\n";
    std::exit(1);
  }

  std::vector<float> vec(512);
  for (std::size_t i = 0; i < vec.size(); ++i) {
    vec[i] = static_cast<float>((i % 13) - 6) * 0.125F;
  }
  double want_fast = 0.0;
  double want_fp3 = 0.0;
  for (std::size_t i = 0; i < 512; ++i) {
    want_fast += static_cast<double>(kFastDequant[i]) * vec[i];
    want_fp3 += static_cast<double>(kFp3Dequant[i]) * vec[i];
  }
  ExpectNear(DotProductQ4_0_ROCMFP4_FAST(kFastBytes, vec, 512),
             static_cast<float>(want_fast), "rocmfp4 fast dot", 1.0e-2F);
  ExpectNear(DotProductQ3_0_ROCMFPX(kFp3Bytes, vec, 512),
             static_cast<float>(want_fp3), "rocmfp3 dot", 1.0e-2F);

  for (int i = 0; i < 8; ++i) {
    const float got = Ue4m3ScaleToFloat(kUe4m3Codes[i]);
    if (std::memcmp(&got, &kUe4m3Spot[i], sizeof(float)) != 0) {
      std::cerr << "Assertion failed: ue4m3 scale byte "
                << static_cast<int>(kUe4m3Codes[i]) << " actual=" << got
                << " expected=" << kUe4m3Spot[i] << '\n';
      std::exit(1);
    }
  }
}

